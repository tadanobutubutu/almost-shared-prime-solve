#!/usr/bin/env python3
# =============================================================================
# Almost Shared Prime - Daily AlpacaHack
# カテゴリー: Crypto | トピック: RSA | 難易度: Hard 8.0
# =============================================================================
# 【概要】
# 前作 Shared Prime の続編です。配布ファイル chall.py は、同じフラグ m を
# 2 つの RSA 公開鍵で暗号化しています。
#
#   n1 = p * q1          n2 = (p + 2) * q2    （p と p + 2 は「双子素数」）
#   c1 = m^e mod n1      c2 = m^e mod n2      （e = 65537）
#   p は 1024 ビット、q1 と q2 は 256 ビットと「小さい」素数です。
#
# 前作と違い、2 つの n は同じ素数を共有していないので gcd(n1, n2) = 1 です。
# しかし p と p + 2 は「ほぼ同じ」なので、
#
#   n1 / n2 = (q1 / q2) * p / (p + 2) ≒ q1 / q2
#
# がものすごく高い精度で成り立ちます。このように「分数 n1/n2 を、分母の小さい分数
# q1/q2 で近似する」問題は、連分数展開（の近似分数 = convergent）で解けます。
#
# 手順:
#   1. n1/n2 を連分数展開し、近似分数 a/b を順番に作る
#   2. n1 % a == 0 かつ n2 % (n1//a + 2) == 0 になる a/b を探す → a = q1, b = q2
#   3. p = n1 // q1 → φ(n1) = (p-1)(q1-1) → d = e^(-1) mod φ(n1) → m = c1^d mod n1
#
# 【準備】
#   pip install pycryptodome
#   問題ページから配布ファイル (almost-shared-prime.tar.gz) を各自ダウンロードし、
#   展開しておいてください。
#
# 【使い方】
#   python3 solve.py [output.txt へのパス]
#   ※ パスを省略した場合は ./almost-shared-prime/output.txt を読み込みます。
#
# ※ フラグはこのファイルには書かれていません。実行時に計算して表示します。
# =============================================================================

import re   # output.txt から "n1 = 123..." の形の行を読み取るため
import sys  # コマンドライン引数の取得用

try:
    # long_to_bytes: 大きな整数を元のバイト列（文字列）に戻す関数。
    # chall.py が暗号化前に使っている bytes_to_long のちょうど逆の操作です。
    from Crypto.Util.number import long_to_bytes
except ImportError:
    sys.exit("[!] pycryptodome が見つかりません。`pip install pycryptodome` を実行してください。")

# =============================================================================
# Step 0: output.txt を読み込む
# =============================================================================
# 配布ファイルはリポジトリに含めていないため、ローカルに展開した output.txt を読みます。
# output.txt は chall.py の print(f"{n1 = }") などの出力で、
#   n1 = <10進数の整数>
# という形の行が n1, n2, c1, c2 の 4 行並んでいます。
DEFAULT_PATH = "./almost-shared-prime/output.txt"
path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_PATH

try:
    with open(path, encoding="utf-8") as f:
        text = f.read()
except FileNotFoundError:
    sys.exit(f"[!] {path} が見つかりません。配布ファイルを展開し、パスを引数で指定してください。")

# 「名前 = 数字」の組を全部拾って辞書にします。Python の int は桁数無制限なので、
# 数百桁の巨大な数でもそのまま扱えます。
values = {name: int(num) for name, num in re.findall(r"(\w+)\s*=\s*(\d+)", text)}
try:
    n1, n2, c1, c2 = values["n1"], values["n2"], values["c1"], values["c2"]
except KeyError as err:
    sys.exit(f"[!] output.txt に {err} が見つかりません。")

# 公開指数 e は output.txt には出力されていませんが、chall.py に e = 65537 と書かれています。
e = 65537

print(f"[*] n1 : {n1.bit_length()} ビット")
print(f"[*] n2 : {n2.bit_length()} ビット")


# =============================================================================
# Step 1: 連分数の「近似分数（convergent）」を順番に作るジェネレータ
# =============================================================================
# 分数 a/b の連分数展開は、ユークリッドの互除法と同じ割り算の繰り返しです。
#
#   a/b = k0 + 1/(k1 + 1/(k2 + 1/(k3 + ...)))     （k_i = 各ステップの商）
#
# 途中で打ち切った分数を「近似分数」と呼び、次の漸化式で計算できます。
#
#   h_i = k_i * h_{i-1} + h_{i-2}     （分子）
#   g_i = k_i * g_{i-1} + g_{i-2}     （分母）
#   初期値: h_{-2} = 0, h_{-1} = 1,  g_{-2} = 1, g_{-1} = 0
#
# 近似分数は「その分母の大きさで作れる分数の中で、元の値に最も近い分数」の候補で、
# 分母が小さいうちから元の値をとても良く近似します。
def get_convergents(a, b):
    """a/b の近似分数 (分子, 分母) を、分母が小さいものから順に返す"""
    h_prev2, h_prev1 = 0, 1   # 分子の 2 つ前・1 つ前
    g_prev2, g_prev1 = 1, 0   # 分母の 2 つ前・1 つ前
    while b != 0:
        k = a // b            # 商 k_i（連分数の i 番目の項）
        a, b = b, a % b       # ユークリッドの互除法と同じ更新
        h = k * h_prev1 + h_prev2
        g = k * g_prev1 + g_prev2
        yield h, g
        h_prev2, h_prev1 = h_prev1, h
        g_prev2, g_prev1 = g_prev1, g


# =============================================================================
# Step 2: n1/n2 の近似分数の中から q1/q2 を探す
# =============================================================================
# n1/n2 = (q1/q2) * p/(p+2) で、p/(p+2) は 1 にとても近い値です。
# ずれの大きさは |n1/n2 - q1/q2| = 2*q1 / (q2*(p+2)) しかありません。
#
# ルジャンドルの定理: |x - a/b| < 1/(2*b^2) なら、既約分数 a/b は x の近似分数のどれかになる。
# 今回は「4*q1*q2 < p + 2」なら条件を満たし、q1*q2 は約 512 ビット、p は 1024 ビットなので
# 余裕で成り立ちます。つまり q1/q2 は n1/n2 の近似分数のどれかとして必ず出てきます。
#
# どれが正解かは分からないので、1 つずつ「本当に割り切れるか」で確かめます。
#   - 分子 a で n1 が割り切れる → p = n1 // a の候補
#   - その p について (p + 2) で n2 も割り切れる → 正解
found = None
for index, (cand_q1, cand_q2) in enumerate(get_convergents(n1, n2)):
    if cand_q1 == 0 or cand_q2 == 0:
        continue  # 最初のほうの近似分数は 0 になることがあるので飛ばす
    if n1 % cand_q1 == 0:
        cand_p = n1 // cand_q1
        if n2 % (cand_p + 2) == 0:
            found = (index, cand_p, cand_q1, cand_q2)
            break

if found is None:
    sys.exit("[!] 近似分数から q1, q2 が見つかりませんでした。")

index, p, q1, q2 = found
print(f"[*] {index + 1} 番目の近似分数で q1/q2 を発見")
print(f"[*] p  : {p.bit_length()} ビット")
print(f"[*] q1 : {q1.bit_length()} ビット")
print(f"[*] q2 : {q2.bit_length()} ビット")

# 念のための確認: 2 つの n がきちんと復元できているか
assert p * q1 == n1
assert (p + 2) * q2 == n2

# =============================================================================
# Step 3: 秘密鍵 d を作って c1 を復号する（ここからは教科書どおりの RSA）
# =============================================================================
# n1 = p * q1（異なる 2 素数の積）なので、オイラーのトーシェント関数は
#   φ(n1) = (p - 1) * (q1 - 1)
# です。d は「e * d ≡ 1 (mod φ(n1))」を満たす数（モジュラ逆元）で、
# Python 3.8 以降では pow(e, -1, phi) で直接計算できます。
phi1 = (p - 1) * (q1 - 1)
d1 = pow(e, -1, phi1)

# RSA の復号: m = c1^d mod n1（pow(底, 指数, 法) は繰り返し二乗法で高速）
m = pow(c1, d1, n1)

# =============================================================================
# Step 4: 整数 m をバイト列に戻して表示する
# =============================================================================
# chall.py は FLAG を bytes_to_long で整数にしてから暗号化しているので、
# long_to_bytes で逆変換すれば元の文字列に戻ります。
flag = long_to_bytes(m)

# （おまけの確認）2 本目の鍵 (n2, c2) からも復号し、同じ m になるか確かめます。
# n2 = (p + 2) * q2 なので φ(n2) = (p + 1) * (q2 - 1) です（(p + 2) - 1 = p + 1）。
d2 = pow(e, -1, (p + 1) * (q2 - 1))
print(f"[*] (n2, c2) からの復号結果と一致: {pow(c2, d2, n2) == m}")

print("[+] Flag:", flag.decode())
